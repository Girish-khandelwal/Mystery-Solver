export function buildCompactCase(
  story: Story,
  index: number,
  meta: CaseMeta,
): { case: MysteryCase; solution: SecretSolution } {
  const [
    culprit,
    first,
    second,
    claim,
    fact,
    lead,
    recovery,
    motive,
    method,
    red,
  ] = story;
  const culpritIndex = index % 3;
  const names = [first, second];
  names.splice(culpritIndex, 0, culprit);
  const culpritId = `person-${culpritIndex}`;
  const evidence: Evidence[] = [
    {
      id: "activity",
      name: "Original activity record",
      type: "Digital",
      locationId: "scene",
      image: "/cases/evidence.svg",
      description:
        "The retained activity record covers the 14:10 incident. Examine it to compare the claimed account with what was recorded.",
      analysis: `14:10 — ${fact}`,
      relatedSuspects: [culpritId],
    },
    {
      id: "lead",
      name: "Opening record and follow-up lead",
      type: "Documents",
      locationId: "records",
      image: "/cases/evidence.svg",
      description:
        "The opening record at 14:00 shows the item or arrangement before the incident. A second entry identifies where to follow the lead.",
      analysis: `14:00 — The opening record confirms the original item or arrangement. ${lead}`,
      relatedSuspects: [],
    },
    {
      id: "finding",
      name: "Recovered corroborating exhibit",
      type: "Physical",
      locationId: "followup",
      image: "/cases/evidence.svg",
      description:
        "An officer secures the follow-up exhibit at 14:20. Compare its identifying details with the original report.",
      analysis: `14:20 — ${recovery}`,
      relatedSuspects: [culpritId],
    },
    {
      id: "motive",
      name: "Earlier correspondence",
      type: "Documents",
      locationId: "records",
      image: "/cases/evidence.svg",
      description:
        "A message or form written before the incident may explain why someone wanted a different outcome.",
      analysis: motive,
      relatedSuspects: [culpritId],
    },
    {
      id: "witnesses",
      name: "Independent witness checks",
      type: "Witness",
      locationId: "scene",
      image: "/cases/evidence.svg",
      description: `${first} and ${second} both give accounts of their whereabouts. Cross-check them against the original record.`,
      analysis: `Continuous reception footage shows ${first} and ${second} together at the public desk from 14:00 to 14:20, away from the recorded act. Their movements are independently accounted for.`,
      relatedSuspects: names
        .map((_, i) => `person-${i}`)
        .filter((id) => id !== culpritId),
    },
    {
      id: "red",
      name: "The suspicious detail",
      type: "Forensic",
      locationId: "scene",
      image: "/cases/evidence.svg",
      description:
        "One witness noticed something suspicious about a different person. Check whether it actually connects to this incident.",
      analysis: red,
      relatedSuspects: [],
    },
  ];
  const suspects: Suspect[] = names.map((name, i) => ({
    id: `person-${i}`,
    name,
    age: 24 + i * 7,
    occupation: "Case participant",
    relationship: `Present at ${meta.subtitle}`,
    personality:
      i === culpritIndex
        ? "Confident about their version of events."
        : "Willing to have their account checked.",
    background: `Their connection to the incident is documented in the scene records at ${meta.subtitle}.`,
    motive:
      "Establish any motive from the earlier correspondence; access alone is not proof.",
    alibi:
      i === culpritIndex
        ? "Says they did not perform the disputed act."
        : "At the public desk with another witness.",
    avatar: "/cases/portrait.svg",
    questions: [
      {
        id: `statement-${i}`,
        prompt: "Describe what you did.",
        answer:
          i === culpritIndex
            ? claim
            : `I was at the public desk with ${name === first ? second : first}. Check the continuous reception footage.`,
      },
      {
        id: `followup-${i}`,
        prompt: "What does the original record change?",
        requires: i === culpritIndex ? ["activity"] : ["witnesses"],
        answer:
          i === culpritIndex
            ? "The record shows more than I said. You should inspect the recovered exhibit and the earlier correspondence before deciding why it happened."
            : "The original footage confirms where I was. A suspicious-looking detail is not always connected to the incident.",
      },
    ],
  }));
  const questions = [
    {
      id: "culprit",
      question: "Who is responsible for the incident?",
      options: names,
    },
    {
      id: "method",
      question: "What did they do?",
      options: [
        method,
        "An unknown outsider entered without leaving any evidence.",
        "The item or arrangement changed by itself, without anyone acting.",
      ],
    },
    {
      id: "motive",
      question: "Which record explains their reason?",
      options: [
        motive,
        "There is no documented reason; the witnesses are simply disliked.",
        "A stranger ordered it, although no message or witness supports that.",
      ],
    },
  ];
  const c: MysteryCase = {
    ...meta,
    date: "21 November 1998",
    setting: meta.subtitle,
    briefing: `${meta.introduction} This is a short introductory investigation. Visit the scene and records desk in either order, analyze the exhibits, and follow the documented lead. Compare a suspect’s exact statement with the original activity record. Every required fact is available in the file.`,
    knownFacts: [
      "The opening record is timed at 14:00.",
      "The reported activity is recorded at 14:10.",
      "Analyze the follow-up lead to open the search location.",
    ],
    locations: [
      {
        id: "scene",
        name: meta.subtitle,
        description:
          "Inspect the original record, speak to witnesses, and examine the suspicious detail.",
        image: meta.coverImage,
        hotspots: [
          {
            evidenceId: "activity",
            label: "Inspect the activity record",
            x: 30,
            y: 35,
          },
          {
            evidenceId: "witnesses",
            label: "Collect witness checks",
            x: 62,
            y: 53,
          },
          {
            evidenceId: "red",
            label: "Examine the suspicious detail",
            x: 42,
            y: 73,
          },
        ],
      },
      {
        id: "records",
        name: "Records desk",
        description:
          "The opening record and earlier correspondence can establish a lead and a reason.",
        image: "/cases/archive.svg",
        hotspots: [
          {
            evidenceId: "lead",
            label: "Read the opening record and lead",
            x: 35,
            y: 50,
          },
          {
            evidenceId: "motive",
            label: "Read earlier correspondence",
            x: 70,
            y: 65,
          },
        ],
      },
      {
        id: "followup",
        name: "Follow-up search",
        description:
          "Inspect the place identified in the analyzed lead. Check the recovered exhibit against the original report.",
        image: "/cases/evidence.svg",
        requires: ["lead"],
        hotspots: [
          {
            evidenceId: "finding",
            label: "Examine the secured exhibit",
            x: 52,
            y: 58,
          },
        ],
      },
    ],
    suspects,
    evidence,
    witnesses: [
      {
        id: "opening-witness",
        name: "Duty records officer",
        statement:
          "The opening record was made at 14:00. The later activity record is timed at 14:10. The search exhibit was secured at 14:20.",
        reliability:
          "Times are taken from the original records, not recalled from memory.",
        requires: ["lead"],
      },
    ],
    timeline: [
      {
        id: "opening",
        title: "14:00 — Original item or arrangement recorded",
        description: "Use the opening record.",
        requires: ["lead"],
      },
      {
        id: "incident",
        title: "14:10 — Disputed activity recorded",
        description: "Use the original activity record.",
        requires: ["activity"],
      },
      {
        id: "search",
        title: "14:20 — Corroborating exhibit secured",
        description: "Use the follow-up finding.",
        requires: ["finding"],
      },
    ],
    deductions: [
      {
        id: "act",
        question:
          "Which explanation is supported by both the activity record and the recovered exhibit?",
        requires: ["activity", "finding"],
        options: [
          questions[1].options[(index % 2) + 1],
          method,
          questions[1].options[index % 2 === 0 ? 2 : 1],
        ],
      },
      {
        id: "reason",
        question: "What explains the person’s reason for acting?",
        requires: ["motive", "witnesses"],
        options: questions[2].options,
      },
      {
        id: "red-herring",
        question: "What should you conclude about the suspicious detail?",
        requires: ["red", "witnesses"],
        options: [
          "It proves the person is guilty, regardless of the other evidence.",
          "It has an independently explained connection to an unrelated activity.",
          "Ignore every witness and rely only on this detail.",
        ],
      },
    ],
    finalQuestions: questions,
  };
  const solution: SecretSolution = {
    answers: { culprit, method, motive },
    deductions: {
      act: method,
      reason: motive,
      "red-herring":
        "It has an independently explained connection to an unrelated activity.",
    },
    contradictions: [
      {
        id: "claim-versus-record",
        pair: [`statement-${culpritIndex}`, "activity"],
        explanation: `The statement “${claim}” conflicts with the original record: ${fact}`,
      },
    ],
    timelineOrder: ["opening", "incident", "search"],
    proof: ["activity", "finding", "motive"],
    hints: [
      "Visit the records desk. Analyze the follow-up lead to open the search location.",
      "Ask each person what they did, then compare the exact statement with the analyzed activity record.",
      `Compare ${culprit}’s first statement with the Original activity record on the evidence board. Attach the activity record, recovered exhibit, and earlier correspondence to your final theory.`,
    ],
    explanation: [
      {
        title: "Who was responsible",
        text: `${culprit} was responsible. Their statement “${claim}” is contradicted by the original record: ${fact}`,
      },
      { title: "What happened", text: method },
      { title: "Why it happened", text: motive },
      { title: "The decisive evidence", text: `${lead} ${recovery}` },
      {
        title: "The order of events",
        text: "At 14:00 the opening record established the starting position. At 14:10 the original activity record captured the disputed act. At 14:20 the follow-up search secured the corroborating exhibit.",
      },
      { title: "The misleading detail", text: red },
    ],
  };
  return { case: c, solution };
}

